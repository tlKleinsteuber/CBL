    public Renderer() {
        initComponents();
        Clock clock = new Clock(5);
        Map world = new Map();
        

        labelNum = world.cities.length;
        cityNameArray = new String[labelNum];
        cityPoints = new Point[labelNum];
        adjacencyMatrix = world.pathMatrix;
        distanceMatrix = new int[labelNum][labelNum];
        
        for (int i = 0; i < labelNum; i++) {
            cityNameArray[i] = world.cities[i].cityName;
            cityPoints[i] = world.cities[i].coords;
            for (int j = 0; j < labelNum; j++) {
                if(adjacencyMatrix[i][j].indexOf(",") != -1) {
                    distanceMatrix[i][j] = Integer.parseInt(adjacencyMatrix[i][j].substring(0, adjacencyMatrix[i][j].indexOf(",")));
                }
            }
        }
        mapRender();
        
        
        DisplayGraphics m=new DisplayGraphics();
        jPanel3.add(m);
        m.setVisible(true);
        m.setSize(500, 500);
        m.setLocation(20, 20);
        revalidate();
        repaint();
        
    }    
    
    
    public void mapRender() {
        Component[] l = new Component[labelNum];
        
        for (int i = 0; i < labelNum; i++) {
            l[i] = jPanel3.add(new JLabel(cityNameArray[i], SwingConstants.CENTER));
            System.out.println(cityNameArray[i]);
            l[i].setSize(cityNameArray[i].length()*15, 15);
            l[i].setVisible(true);
            l[i].setLocation(cityPoints[i].x + 40, cityPoints[i].y + 40);
        }
    }


    
    
    
